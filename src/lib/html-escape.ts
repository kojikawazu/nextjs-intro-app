/**
 * HTML の特殊文字と、その実体参照の対応表。
 *
 * `'` に `&apos;` ではなく数値参照を割り当てているのは、`&apos;` が HTML4 の実体参照に
 * 含まれず、古いメールクライアントでは解決されずに文字列のまま表示されるため。
 * 数値参照はどの処理系でも解釈されるので安全側に倒している。
 *
 * 参照箇所が本ファイルに閉じるため `export` しない
 * （`coding-standards.md`「1 ファイルに閉じる定数はその定義ファイル内に置く」）。
 */
const HTML_ESCAPE_MAP = {
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;',
} as const;

/** `HTML_ESCAPE_MAP` がキーとして持つ文字。 */
type EscapableChar = keyof typeof HTML_ESCAPE_MAP;

/**
 * 文字列を HTML のテキスト／属性値へ安全に埋め込める形にエスケープする。
 *
 * `&`, `<`, `>`, `"`, `'` の 5 文字を実体参照へ置き換える。入力検証（Zod）は
 * 「受け付けてよい値か」を判定するものであり、出力先の文法に合わせる処理ではない。
 * **検証を通った文字列でも、HTML へ埋め込む直前に必ず本関数を通すこと**
 * （`security.md`「XSS: ユーザー入力のサニタイズ + 出力エスケープの多層防御」）。
 *
 * 5 文字を**単一の正規表現でまとめて**置換しているのは二重エスケープを避けるため。
 * `&` → `<` の順に `replace` を重ねると、`<` の置換結果 `&lt;` に含まれる `&` が
 * 後段（または前段の結果）で再度エスケープされ `&amp;lt;` になる。コールバックによる
 * 置換結果は再走査されないため、この方式なら順序を気にせず 1 回で完結する。
 *
 * HTML 以外の出力先（メールの `text` パート・件名・HTTP ヘッダー）には使わない。
 * それらは HTML として解釈されないため、エスケープすると実体参照がそのまま読者に見える。
 *
 * @param value - エスケープ対象の文字列。ユーザー入力など信頼できない値を想定する
 * @returns 特殊文字を実体参照へ置き換えた文字列。対象文字を含まない場合は入力と同じ内容
 */
export function escapeHtml(value: string): string {
    // 正規表現の文字クラスと `HTML_ESCAPE_MAP` のキーは同じ 5 文字で、マッチした時点で
    // `char` は必ずキーのいずれか。TypeScript は `replace` のコールバック引数を `string`
    // としか推論できないため、その対応関係をキャストで補っている（実行時は取りこぼさない）。
    return value.replace(/[&<>"']/g, (char) => HTML_ESCAPE_MAP[char as EscapableChar]);
}
