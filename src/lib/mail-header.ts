/**
 * メールヘッダー（件名など）へ埋め込む値から、ヘッダーの構造を壊す文字を取り除く。
 *
 * メールヘッダーは CRLF で区切られる。値に生の改行が混ざると、そこから先が
 * 別のヘッダーとして解釈され得る（ヘッダーインジェクション）。
 *
 * ```
 * subject: "問い合わせ - 山田\r\nBcc: attacker@example.com"
 *                            ^^^^ ここから別ヘッダー扱いになり得る
 * ```
 *
 * **入力検証（Zod）では代替できない。** 検証は「受け付けてよい値か」の判定であり、
 * 出力先の文法に合わせる処理ではない。`escapeHtml` と同じく**出力の直前**で適用する
 * （`security.md` / docs/06 §8.3）。
 *
 * 除去対象は C0 制御文字（`U+0000`〜`U+001F`）と DEL（`U+007F`）。MIME ヘッダーで
 * 特別な意味を持つのは CR / LF だが、他の制御文字も表示を壊すだけで意味を持たないため
 * まとめて落とす。**空白へ置換せず削除する**のは、値を整形し直すことが目的ではなく
 * 構造を壊す文字を無力化することが目的だから。
 *
 * **本サイトでの実効性の位置づけ**: 送信は Resend の JSON API 経由で、MIME の組み立ては
 * Resend 側が行う。件名は日本語を含むため必ず RFC 2047 のエンコードドワードになり、
 * その中に生の CRLF は入り得ない。したがって注入が成立する可能性は低いが、
 * **Resend は件名の制御文字の扱いを公開していない**ため、多層防御として本関数を通す。
 *
 * @param value - ヘッダーへ埋め込む値。ユーザー入力など信頼できない値を想定する
 * @returns 制御文字を取り除き、前後の空白を落とした文字列
 */
export function sanitizeHeaderValue(value: string): string {
    // 文字クラスに制御文字そのものではなく `\uXXXX` 表記を使うのは、生の制御文字を
    // ソースへ書くと不可視で編集事故を招くため。範囲は C0 全域 + DEL。
    return value.replace(/[\u0000-\u001F\u007F]/g, '').trim();
}
